/**
 * The bash rcfile of agent terminals (`bash --rcfile <runtime>/agent.bashrc -i`, written by
 * src/server.ts): it loads the user's ~/.bashrc, then runs the agent command once
 * ($MIRADOR_AGENT_COMMAND, set by TerminalRegistry.create) and leaves its user in that bash.
 *
 * Every prompt that bash draws is marked with OSC 133 A (the shell-integration prompt mark). bash
 * only draws one when nothing runs in the foreground, so a mark means the agent ended, exited or
 * died, however it did. The registry reports the mark (TerminalRegistry.onStatus) and the attention
 * store drops the agent's OSC 7501 working and blocked records (AttentionStore.programPrompt), as the
 * Program Status Protocol asks when the attached process exits.
 * Without it an agent killed while `blocked` would keep its
 * answer card until the terminal closed.
 *
 * The mark is added after the user's PROMPT_COMMAND (string or, bash 5.1+, array), keeps `$?` for
 * whatever runs after it, and is set before the agent starts: when Ctrl-C kills the agent, bash
 * skips the rest of this file. A readonly PROMPT_COMMAND is left as it is (no mark, no error).
 * Plain bash 3.2 syntax (macOS /bin/bash).
 */
export const AGENT_RC = `# Generated by Mirador: load the user's bashrc, then start the agent once.
[ -f "$HOME/.bashrc" ] && . "$HOME/.bashrc"
# Mark each prompt (OSC 133 A): the agent is no longer running, so Mirador drops its working/blocked status.
__mirador_prompt_mark() { local status=$?; printf '\\033]133;A\\033\\\\'; return "$status"; }
if [[ "$(declare -p PROMPT_COMMAND 2>/dev/null)" =~ ^declare\\ -[A-Za-z]*a ]]; then
  { PROMPT_COMMAND+=(__mirador_prompt_mark); } 2>/dev/null
else
  { PROMPT_COMMAND="\${PROMPT_COMMAND:+\$PROMPT_COMMAND\$'\\n'}__mirador_prompt_mark"; } 2>/dev/null
fi
if [ -n "$MIRADOR_AGENT_COMMAND" ]; then
  __mirador_cmd="$MIRADOR_AGENT_COMMAND"
  unset MIRADOR_AGENT_COMMAND
  history -s "$__mirador_cmd"
  eval "$__mirador_cmd"
  unset __mirador_cmd
fi
`;
