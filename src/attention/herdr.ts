import { chmod, mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { shellQuote, type EnvProvider } from '../terminals/registry.ts';

/**
 * Mirador stands in for herdr (the terminal host gentle-shell knows how to
 * report to) inside agent terminals only:
 *
 * - `HERDR_ENV=1`, `HERDR_PANE_ID` (the terminal id) and `HERDR_SOCKET_PATH`
 *   make gentle-shell treat the terminal as a herdr pane; it only checks that
 *   the socket exists.
 * - gentle-shell reports by running `$HERDR_BIN_PATH pane report-metadata …`.
 *   That is Mirador's shim (bin/herdr-shim), which forwards the call to the
 *   socket as one JSON line. Nothing else is sent: the socket is Mirador's.
 *
 * Everything lives in `<runtimeDir>/herdr` (mode 0700, this user only).
 */
export interface HerdrPaths {
  dir: string;
  socketPath: string;
  binPath: string;
}

export function herdrPaths(runDir: string): HerdrPaths {
  const dir = join(runDir, 'herdr');
  return { dir, socketPath: join(dir, 'socket'), binPath: join(dir, 'herdr') };
}

/** Herdr variables for agent terminals; shell terminals get none. */
export function herdrEnvProvider(paths: Pick<HerdrPaths, 'socketPath' | 'binPath'>): EnvProvider {
  return (info): Record<string, string> =>
    info.kind === 'agent'
      ? { HERDR_ENV: '1', HERDR_PANE_ID: info.id, HERDR_SOCKET_PATH: paths.socketPath, HERDR_BIN_PATH: paths.binPath }
      : {};
}

/**
 * Creates the herdr folder: the `herdr` launcher that runs the shim with
 * Mirador's own node (the agent's PATH may not have one), and `session.json`,
 * where gentle-shell reads the sidebar width that bounds its activity text.
 */
export async function prepareHerdrDir(paths: HerdrPaths, shimPath: string, nodePath = process.execPath): Promise<void> {
  await mkdir(paths.dir, { recursive: true, mode: 0o700 });
  await chmod(paths.dir, 0o700);
  const launcher = `#!/bin/sh\n# Generated by Mirador: the herdr CLI for agent terminals, forwarded to Mirador.\nexec ${shellQuote(nodePath)} ${shellQuote(shimPath)} "$@"\n`;
  await writeFile(paths.binPath, launcher, { mode: 0o700 });
  await chmod(paths.binPath, 0o700);
  await writeFile(join(paths.dir, 'session.json'), JSON.stringify({ sidebar_width: 82 }) + '\n', { mode: 0o600 });
}
